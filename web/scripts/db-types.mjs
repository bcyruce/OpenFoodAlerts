// `make db-types`: regenerate db/generated/{schema,relations}.ts from DATABASE_URL.
//
// drizzle-kit pull introspects the migrated database (ADR 0001: SQL migrations own the
// schema). Two fixes are applied afterwards so the output compiles: column types that
// drizzle-kit cannot map (tsvector, bytea) become custom types, and the SQL/snapshot files
// that pull also writes are removed (migrations are dbmate's job, not drizzle's).
import { execSync } from "node:child_process";
import { readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const out = "db/generated";
const CUSTOM_TYPES = {
  tsvector: "string",
  bytea: "Uint8Array",
};

execSync("pnpm exec drizzle-kit pull", { stdio: "inherit" });

for (const name of readdirSync(out)) {
  if (name.endsWith(".sql") || name === "meta") rmSync(join(out, name), { recursive: true });
}

const header =
  "// GENERATED by `make db-types` (drizzle-kit pull) from db/migrations. Do not edit.\n";

function fixSchema(text) {
  const used = new Set();
  text = text.replace(
    /[ \t]*\/\/ TODO: failed to parse database type '(\w+)'\n(\s*)(\w+): unknown\(("[^"]+")\)/g,
    (match, type, indent, prop, column) => {
      if (!(type in CUSTOM_TYPES)) throw new Error(`no custom type for ${type}: add one`);
      used.add(type);
      return `${indent.replace(/^\n/, "")}${prop}: ${type}(${column})`;
    },
  );
  if (text.includes("unknown(")) throw new Error("unmapped column type left in schema.ts");
  if (used.size === 0) return text;
  const defs = [...used]
    .sort()
    .map((t) => `const ${t} = customType<{ data: ${CUSTOM_TYPES[t]} }>({ dataType: () => "${t}" });`)
    .join("\n");
  return text
    .replace(/^import \{([^}]*)\} from "drizzle-orm\/pg-core"/m, (m, names) => {
      return `import {${names.trimEnd()}, customType } from "drizzle-orm/pg-core"`;
    })
    .replace(/(import \{ sql \} from "drizzle-orm"\n)/, `$1\n${defs}\n`);
}

// drizzle-kit emits tables in catalog order, which differs between databases; sort the
// top-level exports by name so the output only changes when the schema does. Table
// references live in callbacks, so the order does not matter at runtime.
function sortExports(text) {
  const first = text.search(/^export const /m);
  if (first < 0) return text;
  const blocks = text
    .slice(first)
    .split(/^(?=export const )/m)
    .map((b) => b.trimEnd() + "\n");
  blocks.sort((a, b) => a.match(/^export const (\w+)/)[1].localeCompare(b.match(/^export const (\w+)/)[1]));
  return sortImports(text.slice(0, first)) + blocks.join("\n");
}

// The names inside each `import { … }` also come out in catalog order; sort them too.
function sortImports(head) {
  return head.replace(/^import \{([^}]*)\} from (".*")/gm, (m, names, from) => {
    const sorted = names
      .split(",")
      .map((n) => n.trim())
      .filter(Boolean)
      .sort((a, b) => a.localeCompare(b));
    return `import { ${sorted.join(", ")} } from ${from}`;
  });
}

for (const file of ["schema.ts", "relations.ts"]) {
  const path = join(out, file);
  let text = readFileSync(path, "utf8").replace(/\r\n/g, "\n");
  if (file === "schema.ts") text = fixSchema(text);
  text = sortExports(text);
  writeFileSync(path, header + text);
}
