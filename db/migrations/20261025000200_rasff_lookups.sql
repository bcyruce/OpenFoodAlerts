-- RASFF dictionaries that other tables reference (spec §4.1). Rows come from
-- db/seed/rasff/ via `ofa load-seeds`; the other RASFF dictionaries (classification,
-- risk decision, product type, notification basis, action taken) stay seed files only.

-- iso2 is RASFF's alpha2Code: ISO 3166-1 alpha-2 plus XI (Northern Ireland), XK (Kosovo)
-- and a few organisations that RASFF lists as countries (ECDC, EUROPOL, OLAF).
CREATE TABLE countries (
    iso2 text PRIMARY KEY CHECK (iso2 ~ '^[A-Z]{2,10}$'),
    rasff_id integer NOT NULL UNIQUE,
    name_en text NOT NULL,
    name_nl text,
    name_zh text
);

CREATE TABLE hazard_categories (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rasff_id integer NOT NULL UNIQUE,
    name_en text NOT NULL,
    name_nl text,
    name_zh text,
    -- merged T1 label and the taxonomy version that assigned it; filled by ticket 11
    label text,
    taxonomy_version text
);

CREATE TABLE product_categories (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rasff_id integer NOT NULL UNIQUE,
    name_en text NOT NULL,
    name_nl text,
    name_zh text
);

